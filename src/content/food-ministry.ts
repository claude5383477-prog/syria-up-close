export const MINISTRY_CHECKED = "2026-10-27";

type Type = "r" | "c" | "t" | "cf" | "p" | "rp" | "rs" | "rm" | "rc" | "rt";
const TYPE: Record<Type, { ar: string; en: string }> = {
  r: { ar: "مطعم", en: "Restaurant" },
  c: { ar: "مقهى", en: "Cafe" },
  t: { ar: "صالة شاي", en: "Tea room" },
  cf: { ar: "كافيتريا", en: "Cafeteria" },
  p: { ar: "منتزه", en: "Park restaurant" },
  rp: { ar: "مطعم ومسبح", en: "Restaurant and pool" },
  rs: { ar: "مطعم صيفي", en: "Summer restaurant" },
  rm: { ar: "مطعم موسمي", en: "Seasonal restaurant" },
  rc: { ar: "مجمّع مطاعم", en: "Restaurant complex" },
  rt: { ar: "مطعم وصالة شاي", en: "Restaurant and tea room" },
};
const STARS_AR = [
  "",
  "نجمة واحدة",
  "نجمتان",
  "ثلاث نجوم",
  "أربع نجوم",
  "خمس نجوم",
];

const m = (
  type: Type,
  stars: number,
  ar: string,
  en: string,
  hoodAr: string,
  hoodEn: string,
  known?: [ar: string, en: string],
): GuideVenue => {
  const kind =
    type === "c" || type === "t" || type === "cf" ? "cafe" : "restaurant";
  const t = TYPE[type];
  return {
    kind,
    name: { ar, en },
    hood: { ar: hoodAr, en: hoodEn },
    note: {
      ar: `${known ? `${known[0]} ` : ""}${t.ar}، ${STARS_AR[stars]} في دليل وزارة السياحة (تشرين الأول 2026).`,
      en: `${known ? `${known[1]} ` : ""}${t.en}, ${stars}-star class in the Ministry of Tourism directory (October 2026).`,
    },
  };
};

